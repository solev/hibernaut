func TestHostResetKeysOncePerMachineID(t *testing.T) {
	if os.Geteuid() != 0 {
		t.Skip("needs root for the guest reset script")
	}
	dir := t.TempDir()
	write := func() {
		t.Helper()
		for _, name := range []string{"ssh_host_ed25519_key", "ssh_host_ed25519_key.pub"} {
			if err := os.WriteFile(filepath.Join(dir, name), []byte("new key"), 0o600); err != nil {
				t.Fatal(err)
			}
		}
	}
	run := func(id string) {
		t.Helper()
		cmd := exec.CommandContext(t.Context(), "/bin/sh", "-c", resetScript, "hibd-reset", dir, id)
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("reset: %v: %s", err, out)
		}
	}
	gone := func(id string) {
		t.Helper()
		for _, name := range []string{"ssh_host_ed25519_key", "ssh_host_ed25519_key.pub"} {
			if _, err := os.Stat(filepath.Join(dir, name)); !os.IsNotExist(err) {
				t.Errorf("reset retained %s", name)
			}
		}
		if got, err := os.ReadFile(filepath.Join(dir, "key-reset-for")); err != nil || string(got) != id+"\n" {
			t.Error("reset marker doesn't match the machine ID")
		}
	}
	write()
	run("machinea")
	gone("machinea")
	write()
	run("machinea")
	for _, name := range []string{"ssh_host_ed25519_key", "ssh_host_ed25519_key.pub"} {
		if got, err := os.ReadFile(filepath.Join(dir, name)); err != nil || string(got) != "new key" {
			t.Error("stale reset removed a key generated by init")
		}
	}
	run("machineb")
	gone("machineb")
	write()
	lock, err := os.Open(dir)
	if err != nil {
		t.Fatal(err)
	}
	defer lock.Close()
	if err := syscall.Flock(int(lock.Fd()), syscall.LOCK_EX); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(t.Context(), 10*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "/bin/sh", "-c", resetScript, "hibd-reset", dir, "machinec")
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	defer func() {
		cancel()
		if cmd.ProcessState == nil {
			cmd.Wait()
		}
	}()
	waitForResetFlock(t, ctx, cmd.Process.Pid)
	if marker, err := os.ReadFile(filepath.Join(dir, "key-reset-for")); err != nil || string(marker) != "machineb\n" {
		t.Error("reset ran while another process held the directory lock")
	}
	if err := syscall.Flock(int(lock.Fd()), syscall.LOCK_UN); err != nil {
		t.Fatal(err)
	}
	if err := cmd.Wait(); err != nil {
		t.Fatal(err)
	}
	gone("machinec")
}

func waitForResetFlock(t *testing.T, ctx context.Context, pid int) {
	t.Helper()
	children := filepath.Join("/proc", strconv.Itoa(pid), "task", strconv.Itoa(pid), "children")
	for ctx.Err() == nil {
		data, err := os.ReadFile(children)
		if err == nil {
			for _, child := range strings.Fields(string(data)) {
				channel, err := os.ReadFile(filepath.Join("/proc", child, "wchan"))
				if err == nil && strings.Contains(string(channel), "locks_lock_inode_wait") {
					return
				}
			}
		}
		runtime.Gosched()
	}
	t.Fatalf("reset didn't wait for the directory lock: %v", ctx.Err())
}
